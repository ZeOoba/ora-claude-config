<#
  write-fleet.ps1 — Mirrors the Claude scheduled-task fleet into the Obsidian BrainVault.

  Reads the canonical LAMS scheduled-tasks.json registry and renders a live markdown
  table to the vault. Driven by Windows Task Scheduler (every 1 min). Obsidian
  live-renders the note the instant the file changes on disk.

  Robust to session-UUID rotation: tries the verified hardcoded registry path first,
  then auto-discovers the newest non-empty scheduled-tasks.json under the LAMS root.

  Generated by Claude Code 2026-06-03. To remove the whole mirror: delete this folder,
  delete the Windows task "ClaudeFleetMirror", and delete the vault's _Claude folder.
#>
$ErrorActionPreference = 'Stop'

# --- Config ---
$VaultDir   = 'C:\Users\Owner\Obsidian\BrainVault\_Claude'
$OutFile    = Join-Path $VaultDir 'Claude Fleet.md'
$PrimaryReg = Join-Path $env:LOCALAPPDATA 'Packages\Claude_pzs8sxrjxfjjc\LocalCache\Roaming\Claude\local-agent-mode-sessions\a6ad2c61-c3c8-4a48-98a5-e40c1db22ad3\583f08bc-0123-4111-8158-8fe3d927e350\scheduled-tasks.json'
$LamsRoot   = Join-Path $env:LOCALAPPDATA 'Packages\Claude_pzs8sxrjxfjjc\LocalCache\Roaming\Claude\local-agent-mode-sessions'

# --- Helpers ---
function To-Dt([object]$v) {
  if ($null -eq $v) { return $null }
  if ($v -is [datetime]) {
    $d = [datetime]$v
    if ($d.Kind -eq [System.DateTimeKind]::Unspecified) { return [datetime]::SpecifyKind($d, [System.DateTimeKind]::Utc) }
    return $d.ToUniversalTime()
  }
  try {
    return [datetime]::Parse([string]$v, [System.Globalization.CultureInfo]::InvariantCulture,
      [System.Globalization.DateTimeStyles]::AdjustToUniversal -bor [System.Globalization.DateTimeStyles]::AssumeUniversal)
  } catch { return $null }
}

function Get-Relative([object]$v) {
  $t = To-Dt $v
  if ($null -eq $t) { return 'never' }
  $span = [datetime]::UtcNow - $t
  if ($span.TotalSeconds -lt 0)  { return 'just now' }
  if ($span.TotalMinutes -lt 1)  { return 'just now' }
  if ($span.TotalMinutes -lt 60) { return ('{0:N0}m ago' -f [math]::Floor($span.TotalMinutes)) }
  if ($span.TotalHours -lt 24)   { return ('{0:N0}h ago' -f [math]::Floor($span.TotalHours)) }
  return ('{0:N0}d ago' -f [math]::Floor($span.TotalDays))
}

function Local-Stamp([object]$v) {
  $t = To-Dt $v
  if ($null -eq $t) { return '' }
  return $t.ToLocalTime().ToString('MM-dd HH:mm')
}

function Cron-Disp([object]$c) {
  if ([string]::IsNullOrWhiteSpace([string]$c)) { return '_(no schedule)_' }
  return ('`{0}`' -f ([string]$c))
}

function Resolve-Registry {
  if (Test-Path $PrimaryReg) {
    try {
      $j = Get-Content $PrimaryReg -Raw -ErrorAction Stop | ConvertFrom-Json
      if ($j.scheduledTasks -and @($j.scheduledTasks).Count -gt 0) {
        return [pscustomobject]@{ Path = $PrimaryReg; Data = $j }
      }
    } catch {}
  }
  if (Test-Path $LamsRoot) {
    $cands = Get-ChildItem -Path $LamsRoot -Recurse -Filter 'scheduled-tasks.json' -ErrorAction SilentlyContinue |
             Sort-Object LastWriteTime -Descending
    foreach ($c in $cands) {
      try {
        $j = Get-Content $c.FullName -Raw -ErrorAction Stop | ConvertFrom-Json
        if ($j.scheduledTasks -and @($j.scheduledTasks).Count -gt 0) {
          return [pscustomobject]@{ Path = $c.FullName; Data = $j }
        }
      } catch {}
    }
  }
  return $null
}

# --- Build ---
if (-not (Test-Path $VaultDir)) { New-Item -ItemType Directory -Path $VaultDir -Force | Out-Null }

$now = Get-Date
$reg = Resolve-Registry

$sb = New-Object System.Text.StringBuilder
function L([string]$s = '') { [void]$sb.AppendLine($s) }

if ($null -eq $reg) {
  L '---'
  L ('updated: {0}' -f $now.ToString('yyyy-MM-dd HH:mm:ss'))
  L 'source: NONE FOUND'
  L '---'
  L '# Claude Fleet - Scheduled Tasks'
  L ''
  L ('> [!warning] Registry not found as of {0}.' -f $now.ToString('yyyy-MM-dd HH:mm:ss'))
  L '> The session UUID may have rotated, or Claude has not run on this machine yet.'
  $tmp = "$OutFile.tmp"
  [System.IO.File]::WriteAllText($tmp, $sb.ToString())
  Move-Item -Path $tmp -Destination $OutFile -Force
  return
}

$tasks    = @($reg.Data.scheduledTasks)
$enabled  = @($tasks | Where-Object { $_.enabled })
$disabled = @($tasks | Where-Object { -not $_.enabled })

$enabledSorted = $enabled | Sort-Object -Property @{ Expression = {
  $d = To-Dt $_.lastRunAt
  if ($null -eq $d) { [datetime]::MinValue } else { $d }
} } -Descending

L '---'
L ('updated: {0}' -f $now.ToString('yyyy-MM-dd HH:mm:ss'))
L ('total: {0}' -f $tasks.Count)
L ('enabled: {0}' -f $enabled.Count)
L ('disabled: {0}' -f $disabled.Count)
L '---'
L '# Claude Fleet - Scheduled Tasks'
L ''
L ('> Auto-refreshed every 60s. **{0} tasks** - {1} enabled, {2} disabled.' -f $tasks.Count, $enabled.Count, $disabled.Count)
L ('> Last refresh: **{0}**  -  registry: `{1}`' -f $now.ToString('yyyy-MM-dd HH:mm:ss'), (Split-Path $reg.Path -Leaf))
L ''
L ('## Enabled ({0})' -f $enabled.Count)
L ''
L '| Task | Cron | Last run |'
L '|------|------|----------|'
foreach ($t in $enabledSorted) {
  $rel   = Get-Relative $t.lastRunAt
  $stamp = Local-Stamp  $t.lastRunAt
  if ($stamp) { $when = ('{0} ({1})' -f $rel, $stamp) } else { $when = $rel }
  L ('| {0} | {1} | {2} |' -f $t.id, (Cron-Disp $t.cronExpression), $when)
}
L ''
if ($disabled.Count -gt 0) {
  L ('## Disabled ({0})' -f $disabled.Count)
  L ''
  L '| Task | Cron | Last run |'
  L '|------|------|----------|'
  foreach ($t in ($disabled | Sort-Object id)) {
    L ('| {0} | {1} | {2} |' -f $t.id, (Cron-Disp $t.cronExpression), (Get-Relative $t.lastRunAt))
  }
  L ''
}
L '---'
L '*Generated by `write-fleet.ps1` (Task Scheduler: ClaudeFleetMirror). Do not edit - overwritten every minute.*'

# Atomic write so Obsidian never reads a half-written file
$tmp = "$OutFile.tmp"
[System.IO.File]::WriteAllText($tmp, $sb.ToString())
Move-Item -Path $tmp -Destination $OutFile -Force
